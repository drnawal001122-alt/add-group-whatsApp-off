// Detect language from browser
function getSelectedLanguage() {
    const lang = (navigator.language || navigator.userLanguage || 'en').substring(0, 2).toLowerCase();
    return translations[lang] ? lang : 'en'; // Default to English
}

window.currentLanguage = getSelectedLanguage();

// Translate DOM helper
window.translateDOM = function(container) {
    const lang = window.currentLanguage;
    const dict = translations[lang];
    
    // Set direction of body/container
    const dir = lang === 'ar' ? 'rtl' : 'ltr';
    const textAlignment = lang === 'ar' ? 'right' : 'left';
    
    if (container) {
        $(container).attr('dir', dir);
        $(container).css('text-align', textAlignment);
        
        // Translate all elements with data-translate
        $(container).find('[data-translate]').each(function() {
            const key = $(this).attr('data-translate');
            if (dict[key]) {
                if ($(this).is('input') || $(this).is('textarea')) {
                    $(this).attr('placeholder', dict[key]);
                } else {
                    $(this).html(dict[key]);
                }
            }
        });
    }
    
    // Translate static elements outside dynamic container if any
    $('[data-translate-static]').each(function() {
        const key = $(this).attr('data-translate-static');
        if (dict[key]) {
            if ($(this).is('input') || $(this).is('textarea')) {
                $(this).attr('placeholder', dict[key]);
            } else {
                $(this).html(dict[key]);
            }
        }
    });
    
    // Set navbar/footer directions too
    $('.navbar').attr('dir', dir);
    $('.footer').attr('dir', dir);
};

// Initialize static page-level translations when document is ready
$(document).ready(function() {
    window.translateDOM(document.body);
});
